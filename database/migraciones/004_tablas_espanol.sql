-- 004: tablas en español. Solo renombra lo que aún esté en inglés;
-- en BD nuevas (ya creadas en español por 001) no hace nada.
DROP PROCEDURE IF EXISTS renombrar_si_existe;
CREATE PROCEDURE renombrar_si_existe()
BEGIN
  DECLARE n INT;
  SELECT COUNT(*) INTO n FROM INFORMATION_SCHEMA.TABLES WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'users';
  IF n > 0 THEN ALTER TABLE users RENAME TO usuarios; END IF;
  SELECT COUNT(*) INTO n FROM INFORMATION_SCHEMA.TABLES WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'categories';
  IF n > 0 THEN ALTER TABLE categories RENAME TO categorias; END IF;
  SELECT COUNT(*) INTO n FROM INFORMATION_SCHEMA.TABLES WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'services';
  IF n > 0 THEN ALTER TABLE services RENAME TO servicios; END IF;
  SELECT COUNT(*) INTO n FROM INFORMATION_SCHEMA.TABLES WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'service_keywords';
  IF n > 0 THEN ALTER TABLE service_keywords RENAME TO servicio_palabras_clave; END IF;
  SELECT COUNT(*) INTO n FROM INFORMATION_SCHEMA.TABLES WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'branches';
  IF n > 0 THEN ALTER TABLE branches RENAME TO sedes; END IF;
  SELECT COUNT(*) INTO n FROM INFORMATION_SCHEMA.TABLES WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'faqs';
  IF n > 0 THEN ALTER TABLE faqs RENAME TO preguntas_frecuentes; END IF;
  SELECT COUNT(*) INTO n FROM INFORMATION_SCHEMA.TABLES WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'site_settings';
  IF n > 0 THEN ALTER TABLE site_settings RENAME TO ajustes_sitio; END IF;
  SELECT COUNT(*) INTO n FROM INFORMATION_SCHEMA.TABLES WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'audit_logs';
  IF n > 0 THEN ALTER TABLE audit_logs RENAME TO auditoria; END IF;
  SELECT COUNT(*) INTO n FROM INFORMATION_SCHEMA.TABLES WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'news';
  IF n > 0 THEN ALTER TABLE news RENAME TO noticias; END IF;
  SELECT COUNT(*) INTO n FROM INFORMATION_SCHEMA.TABLES WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'login_attempts';
  IF n > 0 THEN ALTER TABLE login_attempts RENAME TO intentos_acceso; END IF;
END;
CALL renombrar_si_existe();
DROP PROCEDURE renombrar_si_existe;
